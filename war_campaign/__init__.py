"""RTS 战争状态机（Phase 3，docs/hng-rts-protocol.md）——war_campaign 包。

职责（自原单文件 war_campaign.py 继承）：
  - 战争生命周期：ensure_war（自动开战，读 WarDatabase capital 表分配初始
    归属）→ running → check_victory（占领首都数达 pointsNeededForVictory
    → end_war + 自动续战）。
  - war 行消息构建（29 REQUIRED 字段全填，docs/hng-rts-protocol.md §3.1）。
  - war catalogue 数据聚合（views.handle_query_war_catalogue_request 用）。

faction id 空间 = factiontemplateid 恒等映射 1/2/3（project_rules 硬约束）。
时间戳 STR 格式 'YYYYMMDDHHMMSSZ'（紧凑 Zulu，客户端统一用
TimeUtilities.convertZuluTimeToMilliseconds 按位截取解析——带 '-'/' '/':' 的
ISO 风格串会截出乱码 → Date.parse NaN → getMorale 士气恒 0）。

阶段 3.5 拆分（docs/warserver-refactor-plan.md §3.5）：单文件拆 11 子模块
（common/lifecycle/war_row/catalogue/battle_msgs/at_ops/warmap_view/
at_movement/supply/tick/production），本 __init__ re-export 全部原顶层符号，
调用方 from war_campaign import X / war_campaign.X 语义不变。

注意：可重绑缓存经包名访问只见 import 时快照——清缓存/直读请打子模块
属性：war_campaign.common._ADJACENCY_CACHE / .common._BF_POS_CACHE /
war_campaign.at_ops._AIRFIELD_CACHE / war_campaign.production._PROD_LAST_RUN。
"""
