"""任务域（mission）：战争地图任务列表 / 加入 / 取消 / 放弃 / 结束 / 点亮 / 创建。

消息 schema（decompiled/proto-files/HnG_States，注意 response 字段号不统一）：
- GetMissionListRequest {characterId=1} → GetMissionListResponse {
    entries=1 repeated MissionListEntry{info=1 MissionInfo,
    factions=2 repeated MissionListFaction{factionId=1, playerCount=2}}}
- CanJoinMissionRequest {missionId=1, characterId=2}
  → CanJoinMissionResponse {response=1}
- JoinMissionRequest {missionId=1, characterId=2, hostingCenterIds=3}
  → JoinMissionResponse {response=1, missionId=2, missionSessionId=3,
    gameConnect=4}
- CancelJoinMissionRequest {DELETEME=1} → CancelJoinMissionResponse {response=2}
- AbandonMissionRequest {} → AbandonMissionResponse {response=1}
- EndMissionRequest {missionId=1, winnerFactionTemplateId=2}
  → EndMissionResponse {missionId=1}
- GreenlightMissionRequest {greenlight=3} → GreenlightMissionResponse {response=2}
- CreateMissionRequest {missionpreset=1, attackerFactionId=3,
  defenderFactionId=4, assaultTeams=5 repeated CreateMissionAssaultTeam,
  factionAMinCount=6, factionBMinCount=7, factionAMaxCount=8,
  factionBMaxCount=9} → CreateMissionResponse {missionId=1}

MissionInfo {missionId=1, battleId=2, missionpreset=3, mapEntityId=5,
  mapEntityTypeId=6, isAutogenerated=7, defenderFactionId=8, status=9,
  hostingCenterId=10, activationTimeStamp=11, weatherTimeOfDay=12,
  weatherCondition=13}

客户端流程（U0 反编译）：
- GreenlightMissionRequest 由 MatchmakingService 发出（greenlight=3 强制开始），
  响应只记日志。
- JoinMissionResponse.gameConnect → ActionGameService.launchActionGame 构造
  ResourceName 进战斗。
- 其余请求在战争地图模块（未完全反编译）发出，实现以不堵塞请求队列为首要目标。
- GetMissionDetailsRequest / JoinMatchMakingRequest / CancelJoinMatchMakingRequest
  已由 matchmaking.py 处理，本模块不重复注册。

mission_records.state：0 组队中 1 运行 2 结束 3 放弃。
"""

