async def handle_create_mission(sess, writer, cmd_id, req_type, proto):
    """CreateMissionRequest {missionpreset=1, attackerFactionId=3,
    defenderFactionId=4, ...} → CreateMissionResponse{missionId=1}。

    玩家创建任务（战争地图）：mission_records 落库（state=0 组队中）。"""
    preset = attacker = defender = 0
    a_min = b_min = a_max = b_max = 0
    try:
        f = pb_parse(proto)
        preset = int(f.get(1, 0) or 0)
        attacker = int(f.get(3, 0) or 0)
        defender = int(f.get(4, 0) or 0)
        a_min = int(f.get(6, 0) or 0)
        b_min = int(f.get(7, 0) or 0)
        a_max = int(f.get(8, 0) or 0)
        b_max = int(f.get(9, 0) or 0)
    except Exception as e:
        log(f'      [mission] CreateMission parse error: {e}')

    pid = await sess.ensure_player()
    mission_id = 0
    if pid is not None and STORE is not None and preset:
        try:
            mission_id = await STORE.create_mission_record(
                preset, attacker_faction=attacker, defender_faction=defender,
                owner_player_id=int(pid),
                name=f'Mission {preset}',
                map_entity_id=MISSION_MAP_ENTITY_ID)
            log(f'      [DB] mission {mission_id} created (preset={preset}, '
                f'A={attacker}, D={defender}, player={pid})')
        except Exception as e:
            log(f'      [DB] create_mission_record failed: {e}')

    resp = build_response(cmd_id, 'CreateMissionResponse',
                          pb_int64(1, mission_id))
    writer.write(resp)
    await writer.drain()
    log(f'S->C cmd={cmd_id:<4} CreateMissionResponse (mission={mission_id}, '
        f'preset={preset}, {a_min}/{a_max}v{b_min}/{b_max})')


