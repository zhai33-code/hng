RC_OK = 1
RC_MISSION_NOT_FOUND = 43

_GAME_CONNECT = f'{PUBLIC_HOST}:5678'    # 与 matchmaking 成局 game_connect 同源（PUBLIC_HOST）


def _str(v):
    if isinstance(v, bytes):
        return v.decode('utf-8', 'replace')
    return str(v)


def _msg_mission_info_from_record(rec, zulu):
    """mission_records 行 → MissionInfo proto。

    天气/时段：记录无天气列，按行 id 从预设池稳定取模（同 id 恒同天气，
    列表反复刷新不跳变）。"""
    m = pb_int64(1, int(rec['id']))              # missionId
    m += pb_int64(2, 0)                          # battleId
    m += pb_int64(3, int(rec['preset'] or AI_MISSIONPRESET))   # missionpreset
    m += pb_int64(5, int(rec['map_entity_id'] or MISSION_MAP_ENTITY_ID))
    m += pb_int64(6, 1)                          # mapEntityTypeId（1=battlefield）
    m += pb_int32(7, 1)                          # isAutogenerated
    m += pb_int64(8, int(rec['defender_faction'] or 0))       # defenderFactionId
    m += pb_int32(9, int(rec['state']))          # status
    m += pb_int64(10, MISSION_HOSTING_CENTER_ID)
    m += pb_string(11, zulu)                     # activationTimeStamp
    tod, cond, _ = WEATHER_PRESETS[int(rec['id']) % len(WEATHER_PRESETS)]
    m += pb_int32(12, tod)                       # weatherTimeOfDay
    m += pb_int32(13, cond)                      # weatherCondition
    return m


def _msg_mission_info_live(mission_id, faction, zulu):
    """matchmaking 运行中会话 → MissionInfo proto（与 GetMissionDetails 同构）。

    匹配池成局的战局（_MM_MISSION_DETAILS 含 'players'）动态取
    preset / mapEntityId / 玩家数；旧路径回退 AI 局常量。
    """
    det = _MM_MISSION_DETAILS.get(int(mission_id))
    if det and 'players' in det:
        m = pb_int64(1, int(mission_id))             # missionId
        m += pb_int64(2, 0)                          # battleId
        m += pb_int64(3, int(det.get('preset') or AI_MISSIONPRESET))
        m += pb_int64(5, int(det.get('map_entity_id') or MISSION_MAP_ENTITY_ID))
        m += pb_int64(6, 1)                          # mapEntityTypeId
        m += pb_int32(7, 1)                          # isAutogenerated
        m += pb_int64(8, int(det.get('defender_faction', 0) or 0))
        m += pb_int32(9, len(det.get('players') or []))   # playerCount
        m += pb_int64(10, MISSION_HOSTING_CENTER_ID)
        m += pb_string(11, zulu)
        m += pb_int32(12, int(det.get('weather_tod', 1)))    # weatherTimeOfDay
        m += pb_int32(13, int(det.get('weather_condition', 0)))  # weatherCondition
        return m
    m = pb_int64(1, int(mission_id))             # missionId
    m += pb_int64(2, 0)                          # battleId
    m += pb_int64(3, AI_MISSIONPRESET)           # missionpreset（AI 局=10）
    m += pb_int64(5, MISSION_MAP_ENTITY_ID)      # mapEntityId（Benoit Village）
    m += pb_int64(6, 1)                          # mapEntityTypeId
    m += pb_int32(7, 1)                          # isAutogenerated
    m += pb_int64(8, 0)                          # defenderFactionId
    m += pb_int32(9, 1)                          # status（运行中）
    m += pb_int64(10, MISSION_HOSTING_CENTER_ID)
    m += pb_string(11, zulu)
    m += pb_int32(12, 1)                         # weatherTimeOfDay
    m += pb_int32(13, 0)                         # weatherCondition
    return m


def _detail_has_player(det, pid):
    """战局详情是否含该玩家（兼容多人 'players' 与旧单人 'player_id' 结构）。"""
    players = det.get('players')
    if players is not None:
        return any(int(p.get('player_id', 0)) == int(pid) for p in players)
    return int(det.get('player_id', 0)) == int(pid)


def _live_session_for(pid):
    """玩家当前活跃的匹配会话（PMS_TO_SESSION）或 None。"""
    for s in PMS_TO_SESSION.values():
        if int(s.get('player_id', 0)) == int(pid):
            return s
    return None


async def handle_get_mission_list(sess, writer, cmd_id, req_type, proto):
    """GetMissionListRequest {characterId=1} → GetMissionListResponse。

    数据源 = matchmaking 运行中会话（live）+ mission_records(state 0/1)，
    按 mission_id 去重；空列表时 entries 整体省略。"""
    try:
        f = pb_parse(proto)
        char_id = int(f.get(1, 0) or 0)
    except Exception as e:
        char_id = 0
        log(f'      [mission] GetMissionList parse error: {e}')

    pid = await sess.ensure_player()
    zulu = _zulu_activated()   # 过去时间：checkIfBattleIsActivated=true，隐藏"战斗准备完毕于xxx"

    # 侧面记录当前选中士兵（GetMissionList 在玩家点进战斗界面时携带
    # characterId，是"当前选中"最频繁的感知点；内存 + DB 双写）
    if pid is not None and char_id:
        try:
            from state import PLAYER_SELECTED_CHAR
            PLAYER_SELECTED_CHAR[int(pid)] = int(char_id)
            await STORE.set_player_selected_char(int(pid), int(char_id))
        except Exception as e:
            log(f'      [DB] set_player_selected_char failed: {e}')

    # 收集任务：{mission_id: (MissionInfo proto, [MissionListFaction proto])}
    entries = {}

    if pid is not None:
        live = _live_session_for(pid)
        if live is not None:
            mid = PMS_TO_MISSION.get(live['pms_id'], 0)
            fac = int(live.get('faction', 0))
            factions = pb_message(2, pb_int64(1, FACTION_ROW_IDS.get(fac, 0)) +
                                  pb_int32(2, 1))
            entries[mid] = pb_message(
                1, _msg_mission_info_live(mid, fac, zulu)) + factions

    if STORE is not None:
        try:
            recs = await STORE.list_missions_by_state([0, 1])
        except Exception as e:
            recs = []
            log(f'      [DB] list_missions_by_state failed: {e}')
        for rec in recs:
            mid = int(rec['id'])
            if mid in entries:
                continue
            factions = pb_message(
                2, pb_int64(1, FACTION_ROW_IDS.get(int(rec['attacker_faction'] or 0), 0)) +
                pb_int32(2, 1))
            factions += pb_message(
                2, pb_int64(1, FACTION_ROW_IDS.get(int(rec['defender_faction'] or 0), 0)) +
                pb_int32(2, 0))
            entries[mid] = pb_message(
                1, _msg_mission_info_from_record(rec, zulu)) + factions

    resp_proto = b''
    for entry in entries.values():
        resp_proto += pb_message(1, entry)

    resp = build_response(cmd_id, 'GetMissionListResponse', resp_proto)
    writer.write(resp)
    await writer.drain()
    log(f'S->C cmd={cmd_id:<4} GetMissionListResponse '
        f'(charId={char_id}, entries={len(entries)})')


async def handle_can_join_mission(sess, writer, cmd_id, req_type, proto):
    """CanJoinMissionRequest {missionId=1, characterId=2}
    → CanJoinMissionResponse{response=1}。"""
    mission_id = char_id = 0
    try:
        f = pb_parse(proto)
        mission_id = int(f.get(1, 0) or 0)
        char_id = int(f.get(2, 0) or 0)
    except Exception as e:
        log(f'      [mission] CanJoinMission parse error: {e}')

    known = mission_id in _MM_MISSION_DETAILS
    if not known and STORE is not None and mission_id:
        try:
            known = await STORE.get_mission_record(mission_id) is not None
        except Exception as e:
            log(f'      [DB] get_mission_record failed: {e}')

    code = RC_OK if (known or not mission_id) else RC_MISSION_NOT_FOUND
    resp = build_response(cmd_id, 'CanJoinMissionResponse', pb_int32(1, code))
    writer.write(resp)
    await writer.drain()
    log(f'S->C cmd={cmd_id:<4} CanJoinMissionResponse '
        f'(mission={mission_id}, response={code})')


async def handle_join_mission(sess, writer, cmd_id, req_type, proto):
    """JoinMissionRequest {missionId=1, characterId=2, hostingCenterIds=3}
    → JoinMissionResponse{response=1, missionId=2, missionSessionId=3,
    gameConnect=4}。

    战争地图加入任务：有活跃 PMS 会话则回真实 pms_id，否则回退生成值；
    完整进战斗流程由 matchmaking（PlayerMissionSession 推送）负责。"""
    mission_id = char_id = 0
    try:
        f = pb_parse(proto)
        mission_id = int(f.get(1, 0) or 0)
        char_id = int(f.get(2, 0) or 0)
    except Exception as e:
        log(f'      [mission] JoinMission parse error: {e}')

    pid = await sess.ensure_player()
    session_id = 0
    if pid is not None:
        live = _live_session_for(pid)
        if live is not None:
            session_id = int(live['pms_id'])

    resp_proto = pb_int32(1, RC_OK)
    resp_proto += pb_int64(2, mission_id)
    resp_proto += pb_int64(3, session_id)
    resp_proto += pb_string(4, _GAME_CONNECT)

    resp = build_response(cmd_id, 'JoinMissionResponse', resp_proto)
    writer.write(resp)
    await writer.drain()
    log(f'S->C cmd={cmd_id:<4} JoinMissionResponse (response=1, '
        f'mission={mission_id}, session={session_id}, connect={_GAME_CONNECT})')


