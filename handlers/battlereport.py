# -*- coding: utf-8 -*-
"""战报域（battlereport）：客户端战报界面读取战斗结算数据。

数据来源：combat.py 的 AnnounceBattleFieldEarningsRequest 结算入库
（battle_reports / battle_report_players，U1 建表）。

消息 schema（decompiled/proto-files/HnG_States，U0 反编译核对）：
- GetBattleReportRequest { repeated int64 missionBattleReportIds = 1 }
  → GetBattleReportResponse { required int32 result = 1;
    repeated ClientBattleReport battleReports = 2 }
  空请求 → 回玩家最近 10 场战报（通知托盘未推 id 的兜底路径）。
- RequestBattleReportVeteranBonusRequest { battleReportId = 1 }
  → Response { result = 1 }（老兵 +25% 结算时已入账，无需补领）
- ClaimBattleReportVeteranBonusRequest {} → Response { result = 1 }

ClientBattleReport 嵌套（required 字段全给，空 repeated 完全省略）：
  f1 missionBattleReportId / f2 mapEntityTypeId / f3 mapEntityId /
  f4 missionPresetId / f6 defenderFactionId / f7 winnerFactionId /
  f8 missionTimeInSeconds / f9 battleStartTime / f10 wasAutogenerated /
  f11 factions{factionId, players{playerId, playerTag, veteranMember,
  playerScore, playerCaptures, playerKills, playerDeaths, squadName,
  characters{characterId, startXp, endXp, ...bonuses=0,
  creditEarnings{valueEarned, veteranBonus}, warfundEarnings 同,
  xpStatValues{statRequirementId, statValue, xpValue},
  ribbons{ribbonTemplateId, startValue, endValue},
  f14-f16 xpAnyFactionQuickplay/xpQuickplay/xpWarBonus=0（无此机制）},
  assaultTeams{name, commandNodeTemplateId, ownerGamerTag, ownerPlayerId},
  resourcesDestroyed/resourcesCaptured{armyResourceCategoryId, value}} /
  f12 capturepoints{capturepointTemplateId, ownerFactionId}
  （BattleReport f7 / ReportMissionStatus f4 终态兜底，combat.py 结算入库）
"""

import json

import matchmaking
from protocol import (
    build_response,
    pb_bool,
    pb_float,
    pb_int32,
    pb_int64,
    pb_message,
    pb_parse_multi,
    pb_string,
    )
from state import STORE, log


def _msg_earnings(value, vet_bonus=0):
    """ClientBattleReportEarnings：f1 valueEarned，f2 veteranBonus。

    f2 是老兵会员 +25% 加成——客户端 RewardsView 总额 = Σ(valueEarned+
    veteranBonus)（MissionBattleReportMediator.setDetailedPlayerInfo）。"""
    m = pb_int32(1, int(value))
    if vet_bonus:
        m += pb_int32(2, int(vet_bonus))
    return m


def _msg_report_character(ch):
    """ClientBattleReportCharacter（characters_json 单条）。"""
    m = b''
    m += pb_int64(1, int(ch.get('characterId', 0) or 0))
    m += pb_int32(2, int(ch.get('startXp', 0) or 0))
    m += pb_int32(3, int(ch.get('endXp', 0) or 0))
    m += pb_int32(4, int(ch.get('xpVetBonus', 0) or 0))  # xpVeteranBonus(+25%实发)
    m += pb_int32(5, 0)                       # xpBoosterBonus
    m += pb_int32(6, 0)                       # xpCampaignBonus
    m += pb_int32(7, 0)                       # xpUnderdogBonus
    m += pb_int32(8, 0)                       # xpSquadVetBonus
    m += pb_int32(9, int(ch.get('xpDailyBonus', 0) or 0))  # 每日首战+50%
    m += pb_message(10, _msg_earnings(ch.get('creditEarned', 0),
                                      ch.get('creditVetBonus', 0)))
    m += pb_message(11, _msg_earnings(ch.get('warfundEarned', 0),
                                      ch.get('warfundVetBonus', 0)))
    m += pb_int32(14, 0)                      # xpAnyFactionQuickplay（无此机制）
    m += pb_int32(15, 0)                      # xpQuickplay（无此机制）
    m += pb_int32(16, 0)                      # xpWarBonus（无此机制）
    for st in ch.get('stats') or []:               # f12 xpStatValues
        if isinstance(st, dict) and st.get('id'):
            stm = pb_int64(1, int(st['id']))       # statRequirementId
            stm += pb_int32(2, int(st.get('value', 0) or 0))
            stm += pb_float(3, float(st.get('xp', 0) or 0))
            m += pb_message(12, stm)
    for rb in ch.get('ribbons') or []:        # f13 ribbons
        if isinstance(rb, dict):              # 新格式：f2/f3 + 加成 + f9 明细
            rid, sv, ev = (int(rb.get('id', 0) or 0),
                           int(rb.get('start', 0) or 0),
                           int(rb.get('end', 0) or 0))
        else:                                 # 旧格式（只存 id）
            rid, sv, ev = int(rb), 0, 1
        if not rid:
            continue
        rbm = pb_int64(1, rid)
        rbm += pb_int32(2, sv)                # startValue
        rbm += pb_int32(3, ev)                # endValue
        if isinstance(rb, dict):
            # f4-f8 XP 加成（点开勋带进度条计入总额：
            # endValue + booster + campaign + underdog + squadVet [+ veteran]）
            rbm += pb_int32(4, int(rb.get('xpVet', 0) or 0))
            rbm += pb_int32(5, int(rb.get('xpBooster', 0) or 0))
            rbm += pb_int32(6, int(rb.get('xpCampaign', 0) or 0))
            rbm += pb_int32(7, int(rb.get('xpUnderdog', 0) or 0))
            rbm += pb_int32(8, int(rb.get('xpSquadVet', 0) or 0))
            # f9 ribbonStatValues：点开勋带的经验明细列表
            # （ClientBattleStatRequirement：S→C 侧 f3 xpValue 是 fixed32
            # float，与 C→S varint 相反——同角色级 f12 xpStatValues）
            for st in rb.get('stats') or []:
                if isinstance(st, dict) and st.get('id'):
                    stm = pb_int64(1, int(st['id']))
                    stm += pb_int32(2, int(st.get('value', 0) or 0))
                    stm += pb_float(3, float(st.get('xp', 0) or 0))
                    rbm += pb_message(9, stm)
        m += pb_message(13, rbm)
    return m


def _msg_report_player(p):
    """ClientBattleReportPlayer（battle_report_players 行）。"""
    m = b''
    m += pb_int64(1, int(p.get('player_id', 0) or 0))
    m += pb_string(2, p.get('gamertag') or '')
    m += pb_bool(3, True)                     # veteranMember（+25% 已含）
    m += pb_int32(4, int(p.get('score', 0) or 0))
    m += pb_int32(5, int(p.get('captures', 0) or 0))
    m += pb_int32(6, int(p.get('kills', 0) or 0))
    m += pb_int32(7, int(p.get('deaths', 0) or 0))
    m += pb_string(8, p.get('squad_name') or '')
    try:
        chars = json.loads(p.get('characters_json') or '[]')
    except Exception:
        chars = []
    for ch in chars:                          # f9 characters
        m += pb_message(9, _msg_report_character(ch))
    return m, (chars[0].get('factionId', 0) if chars else 0)


def _msg_client_battle_report(rep, players):
    """ClientBattleReport（战报行 + 玩家行列表）。"""
    m = b''
    m += pb_int64(1, int(rep['id']))                    # missionBattleReportId
    m += pb_int64(2, 1)                                 # mapEntityTypeId(1=battlefield)
    m += pb_int64(3, matchmaking.MISSION_MAP_ENTITY_ID)  # mapEntityId（Benoit Village）
    m += pb_int64(4, int(rep['mission_preset_id']))
    m += pb_int64(6, int(rep['defender_faction_id']))
    m += pb_int64(7, int(rep['winner_faction_id']))
    m += pb_int32(8, int(rep['mission_time_seconds']))
    m += pb_int32(9, int(rep['battle_start_time']))
    m += pb_bool(10, False)                             # wasAutogenerated

    # f11 factions：按角色 factionId 分组（无角色的归到胜方）
    # factions_json（结算时 force_pool 快照）：{faction: {ats/destroyed/
    # captured}}——f3 参战突击队 / f4 损失 / f5 缴获（C→S 不上报，官服
    # 由 war 侧推导，本服从资源池推导）
    raw_fx = rep.get('factions_json') or '{}'
    if isinstance(raw_fx, str):
        try:
            fx = json.loads(raw_fx)
        except Exception:
            fx = {}
    else:
        fx = raw_fx or {}
    by_faction = {}
    winner = int(rep['winner_faction_id']) or 1
    for p in players:
        pm, faction = _msg_report_player(dict(p))
        faction = int(faction) or winner
        by_faction.setdefault(faction, []).append(pm)
    # fx 里有而无玩家行的阵营也发（保住该方 f3/f4/f5 展示）
    for fkey in fx:
        try:
            by_faction.setdefault(int(fkey), [])
        except (TypeError, ValueError):
            pass
    for faction in sorted(by_faction):
        fm = pb_int64(1, faction)
        for pm in by_faction[faction]:
            fm += pb_message(2, pm)
        ex = fx.get(str(faction)) or fx.get(faction) or {}
        for at in ex.get('ats') or []:                  # f3 assaultTeams
            # war 局：实例名 + 真实 owner（ownerPlayerId/ownerGamerTag →
            # 客户端显示 AT 属主、非本人非好友给加好友按钮）；
            # staged 局无 owner 字段 → ownerPlayerId=0（客户端判自动生成 AT）
            fm += pb_message(3, pb_string(1, at.get('name') or '')
                             + pb_int64(2, int(at.get('tmpl', 0) or 0))
                             + pb_string(3, at.get('tag') or '')
                             + pb_int64(4, int(at.get('owner', 0) or 0)))
        for cat, n in (ex.get('destroyed') or {}).items():  # f4 损失
            if n:
                fm += pb_message(4, pb_int64(1, int(cat))
                                 + pb_int32(2, int(n)))
        for cat, n in (ex.get('captured') or {}).items():   # f5 缴获
            if n:
                fm += pb_message(5, pb_int64(1, int(cat))
                                 + pb_int32(2, int(n)))
        m += pb_message(11, fm)
    # f12 capturepoints：BattlefieldStatusView 战场态势图逐点着色
    # （capturepoints_json：[{id, owner}]，BattleReport f7 / 状态覆盖兜底）
    raw_cps = rep.get('capturepoints_json') or '[]'
    if isinstance(raw_cps, str):
        try:
            cps = json.loads(raw_cps)
        except Exception:
            cps = []
    else:
        cps = raw_cps or []
    for cp in cps:
        if isinstance(cp, dict) and cp.get('id'):
            m += pb_message(12, pb_int64(1, int(cp['id']))
                            + pb_int64(2, int(cp.get('owner', 0) or 0)))
    return m


async def handle_get_battle_report(sess, writer, cmd_id, req_type, proto):
    """GetBattleReportRequest → GetBattleReportResponse（DB 组装）。"""
    report_ids = []
    try:
        fields = pb_parse_multi(proto)
        report_ids = [int(v) for v in fields.get(1, []) if v]
    except Exception as e:
        log(f'      [battlereport] GetBattleReport parse error: {e}')

    pid = await sess.ensure_player()
    if not report_ids and pid is not None and STORE is not None:
        try:
            report_ids = await STORE.list_recent_report_ids(int(pid), 10)
        except Exception as e:
            log(f'      [DB] list_recent_report_ids failed: {e}')

    resp_proto = pb_int32(1, 1)                # result=1 ok
    count = 0
    if STORE is not None:
        for rid in report_ids:
            try:
                got = await STORE.get_battle_report(int(rid))
            except Exception as e:
                log(f'      [DB] get_battle_report({rid}) failed: {e}')
                continue
            if got is None:
                continue
            rep, players = got
            resp_proto += pb_message(2, _msg_client_battle_report(rep, players))
            count += 1

    resp = build_response(cmd_id, 'GetBattleReportResponse', resp_proto)
    writer.write(resp)
    await writer.drain()
    log(f'S->C cmd={cmd_id:<4} GetBattleReportResponse '
        f'(requested={len(report_ids)}, sent={count})')


